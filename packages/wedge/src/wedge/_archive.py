"""Canonical archive members, including the wedge-owned ``__main__.py``.

shiv unpacks an archive's ``site-packages`` into ``$SHIV_ROOT`` or ``~/.shiv``
on the first run of each build. A sandboxed shell often cannot write
``~/.shiv``, and shiv never deletes an old build. wedge therefore replaces
shiv's ``__main__.py`` with ``MAIN_SOURCE``. The launcher picks an XDG cache
root, turns an extraction failure into one coded error, and prunes old builds.
It then calls shiv's own bootstrap. The source is one fixed string, so every
archive carries the same bytes.
"""

from __future__ import annotations

from io import BytesIO
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZIP_STORED, ZipFile

MAIN_SOURCE = '''# -*- coding: utf-8 -*-
"""Generated by wedge. Pick a writable shiv root, then run shiv's bootstrap."""

import json
import os
import re
import shutil
import sys
import time
import zipfile
from pathlib import Path

import _bootstrap
from _bootstrap.environment import Environment

# shiv's lock covers only extraction. A build younger than this may still run in another session.
KEEP_SECONDS = 24 * 60 * 60
DIGEST_SUFFIX = re.compile(r"-[0-9a-f]{12}$")


def _default_root():
    cache = os.environ.get("XDG_CACHE_HOME", "")
    if not os.path.isabs(cache):
        cache = os.path.join(os.path.expanduser("~"), ".cache")
    return os.path.join(cache, "shiv")


def _fail(root, exc):
    message = f"cannot extract this archive into SHIV_ROOT={root}: {exc}; set SHIV_ROOT to a writable directory"
    print(json.dumps({"error": message, "exit_code": 3}), file=sys.stderr)
    sys.exit(3)


def _family(name):
    """A pattern for the build directories of this archive, with or without a content-digest suffix."""
    if name.endswith(".pyz"):
        stem = DIGEST_SUFFIX.sub("", name[: -len(".pyz")])
        return re.compile(re.escape(stem) + r"(-[0-9a-f]{12})?\\.pyz_[0-9a-f]{64}")
    return re.compile(re.escape(name) + r"_[0-9a-f]{64}")


def _prune(target):
    """Delete old builds of this archive; keep the newest other build and any build younger than a day."""
    root = target.parent
    family = _family(Path(sys.argv[0]).resolve().name)
    try:
        siblings = sorted(
            (entry.stat(follow_symlinks=False).st_mtime, entry.name)
            for entry in os.scandir(root)
            if entry.name != target.name and family.fullmatch(entry.name) and entry.is_dir(follow_symlinks=False)
        )
    except OSError:
        return
    cutoff = time.time() - KEEP_SECONDS
    for mtime, name in siblings[:-1]:
        if mtime < cutoff:
            shutil.rmtree(root / name, ignore_errors=True)
            try:
                (root / f".{name}_lock").unlink(missing_ok=True)
            except OSError:
                pass


def main():
    if not os.environ.get(Environment.ROOT):
        os.environ[Environment.ROOT] = _default_root()
    with zipfile.ZipFile(sys.argv[0]) as archive:
        env = Environment.from_json(archive.read("environment.json").decode())
        target = _bootstrap.cache_path(archive, env.root, env.build_id)
        if not (target / "site-packages").exists() or env.force_extract:
            try:
                _bootstrap.extract_site_packages(
                    archive, target, env.compile_pyc, env.compile_workers, env.force_extract
                )
            except OSError as exc:
                _fail(env.root, exc)
            # The build is fresh now; the bootstrap must not extract it a second time.
            os.environ.pop(Environment.FORCE_EXTRACT, None)
            _prune(target)
    _bootstrap.bootstrap()


main()
'''


def canonicalize_archive(path: Path) -> None:
    """Install ``MAIN_SOURCE`` as ``__main__.py``, then sort, normalize, and deflate ZIP members.

    shiv does not sort its bundled bootstrap files. The deflate bytes can vary
    with the zlib build; the content digest ignores them.
    """
    original = path.read_bytes()
    shebang, separator, _ = original.partition(b"\n")
    if not separator or not shebang.startswith(b"#!"):
        raise ValueError(f"shiv output lacks a shebang: {path}")
    with ZipFile(BytesIO(original)) as source, path.open("wb") as output:
        _ = output.write(shebang + separator)
        with ZipFile(output, "w") as target:
            for info in sorted(source.infolist(), key=lambda item: item.filename):
                data = MAIN_SOURCE.encode() if info.filename == "__main__.py" else source.read(info)
                info.date_time = (1980, 1, 1, 0, 0, 0)
                info.create_system = 3
                is_dir = info.filename.endswith("/")
                mode = 0o40755 if is_dir else 0o100644
                info.external_attr = (mode << 16) | (0x10 if is_dir else 0)
                info.compress_type = ZIP_STORED if is_dir else ZIP_DEFLATED
                target.writestr(info, data)
